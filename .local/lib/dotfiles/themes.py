def get_current_theme_key():
    if os.path.exists(THEME_PREF_FILE):
        try:
            with open(THEME_PREF_FILE) as f:
                k = f.read().strip()
                if k in THEMES:
                    return k
        except Exception:
            pass
    return "catppuccin"

def get_current_theme():
    key = get_current_theme_key()
    return THEMES.get(key, THEMES["catppuccin"])

def hex_to_rgba(hex_color, alpha=1.0):
    """Convert hex (#rrggbb) to css rgba(r, g, b, a) string."""
    h = hex_color.lstrip('#')
    if len(h) == 6:
        r = int(h[0:2], 16)
        g = int(h[2:4], 16)
        b = int(h[4:6], 16)
        return f"rgba({r}, {g}, {b}, {alpha})"
    return hex_color

def hex_to_rgb_float(hex_color):
    """Convert hex (#rrggbb) to (r, g, b) float tuple in 0.0..1.0 for Cairo/OpenGL."""
    h = hex_color.lstrip('#')
    if len(h) == 6:
        return (
            int(h[0:2], 16) / 255.0,
            int(h[2:4], 16) / 255.0,
            int(h[4:6], 16) / 255.0,
        )
    return (1.0, 1.0, 1.0)

